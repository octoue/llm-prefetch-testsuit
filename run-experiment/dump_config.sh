#!/bin/bash
# 将当前环境中的实验相关变量写入指定文件
# 用法: source config.env && ./dump_config.sh > "$RESULTS_DIR/config.env"
# 或: 在脚本中 source 后调用，传入输出路径

OUT="${1:-/dev/stdout}"
CONFIG_VARS=(
  MODEL_PATH GPU_MEMORY_UTILIZATION NUM_GPU_BLOCKS_OVERRIDE KV_OFFLOADING_SIZE SWAP_SPACE
  API_PORT API_HOST API_BASE VLLM_LOG VLLM_HOST VLLM_MAX_NUM_SEQS VLLM_BLOCK_SIZE VLLM_TENSOR_PARALLEL_SIZE
  SEED QPS NUM_CONV TRACE TIMEOUT
  LITE_QPS LITE_NUM_CONV LITE_TRACE LITE_FULL_TRACE LITE_TIMEOUT REQUEST_TIMEOUT PREFETCH_LEAD_TIME TB_PORT
  VLLM_SRC PCIE_PROFILER_DIR VLLM_PIPELINE_PARALLEL_SIZE
  LITE_PCIE_TRACE LITE_PCIE_SAMPLING_MODE LITE_PCIE_MAX_INPUT_LENGTH
  LITE_PCIE_TIER_SHORT LITE_PCIE_TIER_MEDIUM LITE_PCIE_TIER_LONG
  LITE_PCIE_NUM_CONV LITE_PCIE_SCHEDULE_MODE LITE_PCIE_PREFETCH_LEAD_TIME
  LITE_PCIE_MEDIUM_TRACE LITE_PCIE_MEDIUM_MAX_INPUT_LENGTH
  LITE_PCIE_MEDIUM_TIER_SHORT LITE_PCIE_MEDIUM_TIER_MEDIUM LITE_PCIE_MEDIUM_TIER_LONG
  LITE_PCIE_MEDIUM_NUM_CONV MEDIUM_NUM_GPU_BLOCKS_OVERRIDE
)

echo "# 实验配置快照 @ $(date '+%Y-%m-%d %H:%M:%S')"
echo "# 来源: config.env + 运行时覆盖"
for v in "${CONFIG_VARS[@]}"; do
  val="${!v}"
  [ -n "$val" ] && echo "$v=$val"
done
